#include <stdio.h>

/*
 * โจทย์ที่ 1: ตั๋วรถเมล์ (BusTicket)
 * ข้อมูลเข้า: ตัวเลขไม่เกิน 6 หลัก 1 จำนวน (เช่น 32341)
 * ข้อมูลส่งออก: ผลรวมของหลักเรื่อยๆ จนเหลือเลขหลักเดียว (3+2+3+4+1 = 13 -> 1+3 = 4)
 */

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;

    // TODO 1: ลูปนอก ทำซ้ำตราบใดที่ n ยังมี 2 หลักขึ้นไป (n >= 10)
    while (n >= 10) {
        int sum = 0;

        // TODO 2: ลูปใน วนแกะบวกเลขทีละหลัก (n % 10 และ n /= 10)
        while (n > 0) {
            sum += n % 10;
            n /= 10;
        }

        // นำผลรวมกลับมาเป็นค่า n รอบใหม่
        n = sum;
    }

    // TODO 3: แสดงผลลัพธ์เลขหลักเดียว พร้อมขึ้นบรรทัดใหม่
    printf("%d\n", n);

    return 0;
}

