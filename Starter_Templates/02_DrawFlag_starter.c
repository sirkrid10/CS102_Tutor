#include <stdio.h>

/*
 * โจทย์ที่ 2: วาดธง (DrawFlag)
 * ข้อมูลเข้า: R และ C (จำนวนแถวและจำนวนคอลัมน์)
 * ข้อมูลส่งออก: รูปธงขนาด R x C สลับ @ และ # (แถวเริ่มด้วย @ เสมอ)
 */

int main() {
    int R, C;
    if (scanf("%d %d", &R, &C) != 2) return 0;

    // TODO 1: ลูปนอก คุมแถว (i จาก 0 ถึง R - 1)
    for (int i = 0; i < R; i++) {

        // TODO 2: ลูปใน คุมคอลัมน์ (j จาก 0 ถึง C - 1)
        for (int j = 0; j < C; j++) {
            // TODO 3: เช็คว่าคอลัมน์คู่ให้พิมพ์ '@' คอลัมน์คี่ให้พิมพ์ '#'
            if (j % 2 == 0) {
                printf("@");
            } else {
                printf("#");
            }
        }

        // TODO 4: ขึ้นบรรทัดใหม่เมื่อพิมพ์ครบหนึ่งแถว
        printf("\n");
    }

    return 0;
}

